/**
 * Definition for singly-linked list.
 * struct ListNode {
 *     int val;
 *     ListNode *next;
 *     ListNode(int x) : val(x), next(NULL) {}
 * };
 */
class Solution {
public:
  ListNode *detectCycle(ListNode *head) {
    if (!head || !head->next)
      return nullptr;
    ListNode *tail = head;

    unordered_set<ListNode *> seen;

    while (tail) {
      if (seen.count(tail))
        return tail;
      seen.insert(tail);
      tail = tail->next;
    }

    return nullptr;
  }
};
